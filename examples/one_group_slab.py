import cockatoo


# ============================================================
# CASE
# ============================================================

case = cockatoo.Case()


# ============================================================
# MATERIAL
# ============================================================

fuel = cockatoo.Material(
    name="fuel",
    D=1.2,
    Sigma_a=0.01,
    nuSigma_f=0.012,
)

case.materials.add(fuel)


# ============================================================
# GEOMETRY
# ============================================================

case.geometry = cockatoo.Slab(
    width=100.0
)


# ============================================================
# MESH
# ============================================================

case.mesh = cockatoo.Cartesian1D(
    nx=100,
    width=100.0,
)


# ============================================================
# PHYSICS
# ============================================================

case.physics = cockatoo.Diffusion(
    groups=1
)


# ============================================================
# SOLVER
# ============================================================

case.solver = cockatoo.PowerIteration(
    tolerance=1e-8
)


# ============================================================
# RUN
# ============================================================

result = cockatoo.run()

result.summary()